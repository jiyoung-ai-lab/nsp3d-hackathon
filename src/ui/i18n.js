let lang = 'ko';
export function t(key) {
  return (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
}
export function getLang() { return lang; }
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
}
export function setLang(v, root = document) {
  lang = v === 'en' ? 'en' : 'ko';
  try { localStorage.setItem(STORE_KEYS.lang, lang); } catch (e) { /* noop */ }
  try { document.documentElement.lang = lang; } catch (e) { /* noop */ }
  applyI18n(root);
  return lang;
}
export function initLang(selectEl, root = document) {
  let v = 'ko';
  try { v = localStorage.getItem(STORE_KEYS.lang) || 'ko'; } catch (e) { /* noop */ }
  lang = v === 'en' ? 'en' : 'ko';
  if (selectEl) selectEl.value = lang;
  try { document.documentElement.lang = lang; } catch (e) { /* noop */ }
  applyI18n(root);
  return lang;
}
